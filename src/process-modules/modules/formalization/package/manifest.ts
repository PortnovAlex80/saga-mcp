/**
 * The central, validated ProcessModuleManifest for the Solution Formalization
 * package.
 *
 * This is the single object Wave 8 hands to the installer: it wraps the
 * existing pure {@link formalizationProcessModule} definition and declares the
 * pinned resources, handlers and contracts the module depends on. Other W8
 * lanes submit entries to A1, which reconciles them HERE — never edit this
 * constant from another lane.
 *
 * The manifest is validated at module load by
 * {@link validateProcessModuleManifest} (W1-A2), which enforces both canonical
 * serializability (plan §3.5 — no functions/Map/Set/class instances/undefined-
 * in-arrays/Symbols/non-finite numbers) and structural completeness (required
 * fields present, `logicalId`s unique, `resourceIndex` kinds known). A
 * regression throws synchronously and fails the build — the manifest is the
 * load-bearing seam between the pure definition and the content-addressed
 * package, so it must never load in an invalid state.
 */
export const formalizationPackageManifest: ProcessModuleManifest = (() => {
  const manifest: ProcessModuleManifest = {
    manifestFormatVersion: FORMALIZATION_MANIFEST_FORMAT_VERSION,
    definition: formalizationProcessModule,
    resourceIndex: FORMALIZATION_RESOURCE_INDEX,
    handlerRefs: FORMALIZATION_HANDLER_REFS,
    inputContractRef: FORMALIZATION_INPUT_CONTRACT_REF,
    outputContractRef: FORMALIZATION_OUTPUT_CONTRACT_REF,
    runtimeCompatibilityRange: FORMALIZATION_RUNTIME_COMPATIBILITY_RANGE,
    assistance: FORMALIZATION_AGENT_ASSISTANCE,
  };
  const validation = validateProcessModuleManifest(manifest);
  if (!validation.ok) {
    const rendered = validation.errors
      .map((e) => `  at ${e.path}: [${e.code}] ${e.message}`)
      .join('\n');
    throw new Error(
      `formalization package manifest failed validation:\n${rendered}`,
    );
  }
  return manifest;
})();

