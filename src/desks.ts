import type { GateCheck } from './kernel/gate.js';

// СТОЛ — единица сборки завода.
//
// saga4 сформулировала принцип LEGO (CONVEYOR-MENTAL-MODEL §3): пакет цеха
// декларирует ЧТО (поток, навыки, контракты продукта, планы проверок,
// политики), рантайм владеет КАК (диспетчеризация, воркеры, столы, гейты,
// восстановление). saga5 унаследовала рантайм, но декларации остались
// захардкоженными графами в TypeScript — то есть половина принципа не
// работала: чтобы добавить цех, нужно было писать код и копировать узлы.
//
// Здесь декларация становится ДАННЫМИ, которые оператор собирает:
//
//   Стол = навык + вход + инструменты + хуки + приёмка + обратная связь + выход
//   Цех  = упорядоченный список столов
//
// Граф (язык n8n) больше не пишется руками — он КОМПИЛИРУЕТСЯ из столов
// (`compileWorkshop`). Поэтому копипаста узлов между цехами структурно
// невозможна: `product` — это [brief, srs], где brief тот же самый стол, что
// и в `discovery`, а не его копия.

/** Навык — многоразовый контракт работы: кто работает, по каким правилам и
 *  что считается приёмкой. Критерии приёмки принадлежат НАВЫКУ: «в брифе пять
 *  разделов» — это часть значения слова «бриф», а не отдельная настройка. */
export interface Skill {
  id: string;
  title: string;
  /** Роль исполнителя — первая строка промпта. */
  role: string;
  /** Инструкция: что сделать. */
  instruction: string;
  /** Требование к формату результата. */
  output?: string;
  /** Заголовок входного материала. Если задан — вход подставляется как
   *  {{text}} в конце промпта; если нет — плейсхолдеры стоят в инструкции
   *  (навык работает с полями item, например {{title}}). */
  input_label?: string;
  /** Исполнимые критерии приёмки этого навыка. */
  checks: GateCheck[];
}

/** Инструмент — то, что столу РАЗРЕШЕНО, сверх «прочитать вход и сдать текст».
 *  Набор намеренно маленький: инструмент добавляется, когда без него нельзя
 *  собрать реальный цех, а не «на будущее». */
export type DeskTool =
  /** Приложить к промпту принятый артефакт продукта (контекст, не вход). */
  | { kind: 'attach'; path: string; label?: string };

/** Хук — детерминированный шаг вокруг воркера. Не модель: скрипт или команда.
 *  Именно `command` делает завод «под ключ»: приёмка может требовать, чтобы
 *  программа реально запускалась, а не чтобы модель это пообещала. */
export type DeskHook =
  /** Ответ модели — JSON-массив; каждый элемент становится отдельным item. */
  | { kind: 'json_array' }
  /** Переписать item по шаблону. */
  | { kind: 'template'; template: string }
  /** Каждый item узнаёт, что делают соседи по вееру (сводка по всем items). */
  | { kind: 'siblings'; field?: string; pick?: string[] }
  /** Выполнить команду и вернуть исход как материал.
   *  `workdir: 'items'` — судить КАНДИДАТА (items {path, content}) во временном
   *  каталоге, то есть ДО публикации: «публикуем только то, что запускается».
   *  По умолчанию команда выполняется в продуктовом репозитории. */
  | { kind: 'command'; run: string; timeout_s?: number; label?: string; workdir?: 'items' };

export type DeskInput =
  /** Стартовый текст оператора (идея, задание). */
  | { kind: 'operator'; field?: string; label?: string }
  /** Принятый материал предыдущего стола этого же прогона. */
  | { kind: 'desk'; desk: string }
  /** То, что предыдущий стол ПОЛОЖИЛ В РЕПОЗИТОРИЙ (ждём эффект, не приёмку).
   *  Нужно столам, которые работают с файлами продукта, а не с текстом. */
  | { kind: 'publish'; desk: string }
  /** Принятый артефакт продукта по пути (между прогонами). `field` даёт
   *  оператору возможность передать материал руками вместо артефакта. */
  | { kind: 'artifact'; path: string; field?: string; label?: string };

export interface DeskPublish {
  /** Путь в продуктовом репозитории. */
  path?: string;
  /** Поле item, из которого берётся содержимое (по умолчанию text). */
  field?: string;
  /** Каждый item — отдельный файл {path, content}. */
  files_from?: 'items';
  message?: string;
  /** Что публикуем. По умолчанию — материал самого стола; `input` означает
   *  «то, что этот стол принял на вход» — так работает стол интеграции:
   *  ревьюер одобряет чужой материал, и публикуется именно он. */
  from?: 'own' | 'input';
}

export interface Desk {
  id: string;
  title: string;
  /** Навык исполнителя. Столу без навыка (стол приёмки) работу делает хук —
   *  например команда, которая запускает программу. */
  skill?: string;
  input: DeskInput;
  /** Столы, которые обязаны закончить раньше. Их материал приходит воркеру
   *  как КОНТЕКСТ (например, замечания ревьюера сборщику), а вход стола
   *  остаётся тем, что объявлен в `input`: порядок и материал — разные вещи. */
  depends_on?: string[];
  /** Динамический fan-out: по воркеру на каждый входной item. */
  fanout?: boolean;
  tools?: DeskTool[];
  /** `before` — подготовка входа (разбор JSON предыдущего стола);
   *  `after`  — производство доказательств ДО приёмки (запуск команды).
   *  Преобразование уже принятого материала — это `before` следующего стола. */
  hooks?: { before?: DeskHook[]; after?: DeskHook[] };
  /** Критерии сверх навыковых. */
  checks?: GateCheck[];
  /** Бюджет доработок до человеческого гейта. */
  max_repairs?: number;
  publish?: DeskPublish;
  model?: string;
  /** Таймауты воркера этого стола. */
  timeouts?: { heartbeat_s?: number; start_to_close_s?: number; schedule_to_start_s?: number };
}

export interface WorkshopSpec {
  id: string;
  title: string;
  desks: Desk[];
}

/** Имена узлов выводятся из id стола — детерминированно и читаемо: по имени
 *  узла на доске сразу видно, чей это стол и какая это его часть. */
export const nodeNames = (deskId: string) => ({
  input: `${deskId}_input`,
  before: (index: number) => `${deskId}_pre${index + 1}`,
  worker: deskId,
  split: `${deskId}_tasks`,
  join: `${deskId}_merge`,
  after: (index: number) => `${deskId}_post${index + 1}`,
  gate: `${deskId}_gate`,
  publish: `${deskId}_publish`,
});
